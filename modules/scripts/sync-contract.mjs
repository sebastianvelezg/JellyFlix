// Copies modules/contract/index.ts to web/src/core/modules/contract.ts (the web build cannot import from outside web/).
//   npm run contract:sync     writes the copy
//   npm run contract:check    fails when the copy is out of date (the CI runs this)
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const source = fileURLToPath(new URL('../contract/index.ts', import.meta.url))
const target = fileURLToPath(new URL('../../web/src/core/modules/contract.ts', import.meta.url))
const banner = '// GENERATED by `npm run contract:sync` in modules/ from modules/contract/index.ts. Do not edit this file: edit the source and run the script.\n'
const wanted = banner + readFileSync(source, 'utf8')

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
  if (current !== wanted) {
    console.error('web/src/core/modules/contract.ts is out of date. Run `npm run contract:sync` in modules/ and commit the result.')
    process.exit(1)
  }
  console.log('The contract copy is up to date.')
} else {
  writeFileSync(target, wanted)
  console.log('Wrote web/src/core/modules/contract.ts')
}
